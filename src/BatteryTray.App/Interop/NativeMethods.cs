    public static ushort LoWord(nint value) => (ushort)((long)value & 0xFFFF);

    public static ushort HiWord(nint value) => (ushort)(((long)value >> 16) & 0xFFFF);

    /// <summary>Copia un texto a un búfer fijo de C, recortándolo y terminándolo en nulo.</summary>
    public static void CopyToFixed(string value, char* destination, int capacity)
    {
        int length = Math.Min(value.Length, capacity - 1);
        value.AsSpan(0, length).CopyTo(new Span<char>(destination, capacity));
        destination[length] = '\0';
    }
